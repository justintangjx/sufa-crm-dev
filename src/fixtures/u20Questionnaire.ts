import type {
  QuestionnaireAudienceScope,
  QuestionnaireImportSourceRow,
} from "../lib/questionnaireImport";

function likert(
  sectionOrder: number,
  sectionTitle: string,
  questionOrder: number,
  prompt: string,
  audience: QuestionnaireAudienceScope,
  subjectKind: QuestionnaireImportSourceRow["subjectKind"],
): QuestionnaireImportSourceRow {
  return {
    sectionOrder,
    sectionTitle,
    questionOrder,
    prompt,
    answerType: "likert",
    scaleMin: 1,
    scaleMax: 5,
    scaleLowLabel: "Strongly disagree",
    scaleHighLabel: "Strongly agree",
    subjectKind,
    audience,
    required: true,
  };
}

function text(
  sectionOrder: number,
  sectionTitle: string,
  questionOrder: number,
  prompt: string,
  audience: QuestionnaireAudienceScope,
  subjectKind: QuestionnaireImportSourceRow["subjectKind"],
): QuestionnaireImportSourceRow {
  return {
    sectionOrder,
    sectionTitle,
    questionOrder,
    prompt,
    answerType: "text",
    scaleMin: null,
    scaleMax: null,
    scaleLowLabel: null,
    scaleHighLabel: null,
    subjectKind,
    audience,
    required: false,
  };
}

